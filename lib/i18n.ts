const DICTS: Record<Locale, Record<MessageKey, string>> = { en, ru, ar };

export type Params = Record<string, string | number>;

/** Look up a key and substitute `{placeholders}`. */
export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Params,
): string {
  const raw = DICTS[locale][key] ?? DICTS[DEFAULT_LOCALE][key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in params ? String(params[name]) : m,
  );
}

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

/**
 * Number grouping follows the interface language, not the browser.
 * Arabic keeps Latin digits (`-u-nu-latn`): coordinates and levels have to be
 * comparable with what the game itself shows.
 */
export function numberLocale(locale: Locale): string {
  return locale === "ru" ? "ru-RU" : locale === "ar" ? "ar-u-nu-latn" : "en-US";
}
